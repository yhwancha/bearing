export type Lang = 'en' | 'ko'
export const LANGS: { code: Lang; label: string }[] = [
  { code: 'en', label: 'English' },
  { code: 'ko', label: '한국어' },
]
const DICTS: Record<Lang, Dict> = { en, ko }
/** Locale used for numbers and dates. Singapore English: 24 Oct 2026, 1,234.50 */
const LOCALES: Record<Lang, string> = { en: 'en-SG', ko: 'ko-KR' }
const KEY = 'bearing.lang'

function initial(): Lang {
  try {
    const saved = localStorage.getItem(KEY)
    if (saved === 'en' || saved === 'ko') return saved
  } catch {
    // storage blocked: fall through to the browser language
  }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('ko') ? 'ko' : 'en'
}

let lang: Lang = typeof window === 'undefined' ? 'en' : initial()

/* Live bindings: modules read `t` and `LOCALE` at render time, and the app remounts on change. */
export let t: Dict = DICTS[lang]
export let LOCALE = LOCALES[lang]

const listeners = new Set<() => void>()

export function getLang(): Lang {
  return lang
}

export function setLang(next: Lang) {
  if (next === lang) return
  lang = next
  t = DICTS[next]
  LOCALE = LOCALES[next]
  try {
    localStorage.setItem(KEY, next)
  } catch {
    // not persisted; still switches for this visit
  }
  if (typeof document !== 'undefined') document.documentElement.lang = next
  listeners.forEach((l) => l())
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (cb) => {
      listeners.add(cb)
      return () => listeners.delete(cb)
    },
    getLang,
  )
}
